package com.shipyard.common.exception;

import lombok.Getter;

/**
 * 业务异常 — Service 层抛, 由 {@link GlobalExceptionHandler} 统一转 {@code ApiResponse}.
 *
 * <p>用法:
 * <pre>{@code
 * if (projectMapper.selectCount(...) > 0) {
 *     throw new BusinessException(ErrorCode.RESOURCE_CONFLICT, "项目名已存在: " + name);
 * }
 * }</pre>
 */
@Getter
public class BusinessException extends RuntimeException {

    private final ErrorCode errorCode;

    public BusinessException(ErrorCode errorCode) {
        super(errorCode.getMessage());
        this.errorCode = errorCode;
    }

    public BusinessException(ErrorCode errorCode, String message) {
        super(message);
        this.errorCode = errorCode;
    }

    public BusinessException(ErrorCode errorCode, String message, Throwable cause) {
        super(message, cause);
        this.errorCode = errorCode;
    }
}
